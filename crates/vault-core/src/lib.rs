/// Shared adversarial fixture vectors run inside each actual platform runtime.
/// Uses public test-only data and returns no sensitive diagnostics.
pub fn run_core_proof() -> Result<()> {
    let expected = validate_event(EVENT_JSON)?;
    let mut base: serde_json::Value = serde_json::from_slice(EVENT_JSON)
        .map_err(|_| FoundationError::new(ErrorCode::Malformed))?;
    for (field, value, code) in [
        (
            "content",
            serde_json::json!("changed"),
            ErrorCode::InvalidId,
        ),
        (
            "created_at",
            serde_json::json!(1700000001),
            ErrorCode::InvalidId,
        ),
        (
            "tags",
            serde_json::json!([["changed"]]),
            ErrorCode::InvalidId,
        ),
        (
            "id",
            serde_json::json!("00".repeat(32)),
            ErrorCode::InvalidId,
        ),
        (
            "sig",
            serde_json::json!("00".repeat(64)),
            ErrorCode::InvalidSignature,
        ),
        ("pubkey", serde_json::json!("not hex"), ErrorCode::Malformed),
    ] {
        let original = base[field].clone();
        base[field] = value;
        let bytes =
            serde_json::to_vec(&base).map_err(|_| FoundationError::new(ErrorCode::Malformed))?;
        if validate_event(&bytes).err().map(|e| e.code) != Some(code) {
            return Err(FoundationError::new(ErrorCode::Crypto));
        }
        base[field] = original;
    }
    for (bytes, code) in [
        (b"{".to_vec(), ErrorCode::Malformed),
        (vec![0; MAX_EVENT + 1], ErrorCode::Limit),
        (
            include_bytes!("../fixtures/out-of-scope.json").to_vec(),
            ErrorCode::OutOfScope,
        ),
    ] {
        if validate_event(&bytes).err().map(|e| e.code) != Some(code) {
            return Err(FoundationError::new(ErrorCode::Crypto));
        }
    }
    let key = derive_key(b"foundation password", &[1; 16])?;
    let known = [
        0xea, 0xf5, 0xc0, 0xec, 0xb5, 0x02, 0xe7, 0x31, 0x36, 0x52, 0x4e, 0xc0, 0x17, 0x62, 0x30,
        0xe8, 0x88, 0x21, 0x87, 0x3f, 0xad, 0xbf, 0xde, 0x2d, 0x16, 0x56, 0x72, 0x14, 0xc9, 0xc8,
        0x9a, 0x72,
    ];
    if *key != known {
        return Err(FoundationError::new(ErrorCode::Crypto));
    }
    let random = RandomMaterial {
        salt: [1; 16],
        data_key: [2; 32],
        wrap_nonce: [3; 24],
        record_nonce: [4; 24],
    };
    let encrypted = protect_record(
        b"foundation password",
        ZIP_BYTES,
        &expected.pubkey,
        "fixture",
        &random,
    )?;
    if *open_record(
        b"foundation password",
        &encrypted,
        &expected.pubkey,
        "fixture",
    )? != ZIP_BYTES
    {
        return Err(FoundationError::new(ErrorCode::Crypto));
    }
    let other_random = RandomMaterial {
        salt: [1; 16],
        data_key: [9; 32],
        wrap_nonce: [3; 24],
        record_nonce: [4; 24],
    };
    let mut wrong_key = encrypted.clone();
    wrong_key.wrapped_key = protect_record(
        b"foundation password",
        ZIP_BYTES,
        &expected.pubkey,
        "fixture",
        &other_random,
    )?
    .wrapped_key;
    if open_record(
        b"foundation password",
        &wrong_key,
        &expected.pubkey,
        "fixture",
    )
    .is_ok()
    {
        return Err(FoundationError::new(ErrorCode::Crypto));
    }
    for mutation in 0..7 {
        let mut changed = encrypted.clone();
        match mutation {
            0 => changed.ciphertext[0] ^= 1,
            1 => changed.wrapped_key[0] ^= 1,
            2 => changed.record_nonce[0] ^= 1,
            3 => changed.wrap_nonce[0] ^= 1,
            4 => changed.salt[0] ^= 1,
            5 => {
                changed.ciphertext.pop();
            }
            _ => changed.version += 1,
        }
        if open_record(
            b"foundation password",
            &changed,
            &expected.pubkey,
            "fixture",
        )
        .is_ok()
        {
            return Err(FoundationError::new(ErrorCode::Crypto));
        }
    }
    for (password, account, record) in [
        (b"wrong".as_slice(), expected.pubkey.as_str(), "fixture"),
        (b"foundation password".as_slice(), "wrong", "fixture"),
        (
            b"foundation password".as_slice(),
            expected.pubkey.as_str(),
            "wrong",
        ),
    ] {
        if open_record(password, &encrypted, account, record).is_ok() {
            return Err(FoundationError::new(ErrorCode::Crypto));
        }
    }
    Ok(())
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn shared_core_vectors() {
        run_core_proof().unwrap();
    }
    #[test]
    fn rejects_contract_mutations_before_work() {
        let base = serde_json::json!({"version":1,"requestId":"test-1","operation":"foundation_proof","eventLength":EVENT_JSON.len(),"payloadLength":ZIP_BYTES.len()});
        for (field, value) in [
            ("version", serde_json::json!(2)),
            ("operation", serde_json::json!("unknown")),
            ("requestId", serde_json::json!("")),
            ("eventLength", serde_json::json!(0)),
            ("payloadLength", serde_json::json!(0)),
            ("version", serde_json::json!("1")),
        ] {
            let mut changed = base.clone();
            changed[field] = value;
            let result = serde_json::from_value::<FoundationRequest>(changed)
                .ok()
                .and_then(|r| r.validate(EVENT_JSON, ZIP_BYTES).ok());
            assert!(result.is_none(), "{field}");
        }
        let mut missing = base.clone();
        missing.as_object_mut().unwrap().remove("version");
        assert!(serde_json::from_value::<FoundationRequest>(missing).is_err());
        let valid: FoundationRequest = serde_json::from_value(base).unwrap();
        assert!(valid.validate(EVENT_JSON, ZIP_BYTES).is_ok());
        assert_eq!(
            valid
                .validate(EVENT_JSON, &vec![0; MAX_PAYLOAD + 1])
                .unwrap_err()
                .code,
            ErrorCode::Limit
        );
    }
}
